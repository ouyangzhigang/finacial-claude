# dedupe by code
seen=set(); CANDS=[]
for c,n,s in RAW:
    if c in seen: continue
    seen.add(c); CANDS.append((c,n,s))

def sym(c): return 'sh'+c if c[0] in '69' else 'sz'+c

# Phase 1: quote + factors (tencent, reliable)
syms=[sym(c) for c,_,_ in CANDS]
q=C.quote(syms)
phase1={}
for c,n,s in CANDS:
    rec=q.get(c)
    f=C.factors(sym(c))
    it={'code':c,'name':n,'sector':s}
    if rec:
        it.update({'price':rec.get('price'),'pe':rec.get('pe_ttm'),'mktcap':rec.get('mktcap_yi'),
                   'turnover':rec.get('turnover'),'float_mktcap':rec.get('float_mktcap_yi')})
    if f:
        it.update({'m5':f.get('m5'),'m10':f.get('m10'),'m20':f.get('m20'),
                   'amt20':f.get('amt20_yi'),'above_ma20':f.get('above_ma20'),'above_ma5':f.get('above_ma5')})
    phase1[c]=it
    time.sleep(0.05)

# Filter: price<=41 (1w账户), m20<=-10 (超跌), pe in (3,80) or pe<0(亏损扭转候选), m5<20(未透支)
survivors=[]
for c,it in phase1.items():
    p=it.get('price'); pe=it.get('pe'); m20=it.get('m20'); m5=it.get('m5')
    if p is None or p>41: continue
    if m20 is None or m20>-10: continue   # 超跌要求 m20<=-10
    if m5 is not None and m5>20: continue  # 近5日已透支
    if pe is not None and pe>120: continue  # 估值过高
    survivors.append(it)

print(json.dumps({'phase1_total':len(phase1),'survivors':len(survivors),
                  'survivors_list':survivors}, ensure_ascii=False, indent=1))
