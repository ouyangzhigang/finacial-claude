# deduplicate
seen = set()
candidates = []
for c in candidates_raw:
    code = c[0]
    if code not in seen:
        seen.add(code)
        candidates.append(c)

print(f'Total unique candidates: {len(candidates)}')

# Get all quotes
all_codes = [c[0] for c in candidates]
all_quotes = {}
for i in range(0, len(all_codes), 50):
    batch = all_codes[i:i+50]
    codes_str = ','.join(batch)
    try:
        q = tencent_quote(codes_str)
        all_quotes.update(q)
    except Exception as e:
        print(f'Batch error: {e}')

print(f'Got {len(all_quotes)} quotes')

# Build final candidate pool
pool = []
for code, name, sector, source, catalyst in candidates:
    code_no_prefix = code[2:] if code.startswith(('sh','sz')) else code
    q = all_quotes.get(code_no_prefix, {})
    price = q.get('price', 0)
    mktcap = q.get('mktcap', 0)
    pe = q.get('pe', 0)
    if price == 0:
        continue

    affordable = '是' if price < 40 else '否'

    pool.append({
        'code': code_no_prefix,
        'name': q.get('name', name),
        'codeRaw': code,
        'sector': sector,
        'source': source,
        'catalyst': catalyst,
        'price': price,
        'marketCapYi': mktcap,
        'pe': pe,
        'affordable1w': affordable
    })

# Sort by sector priority: 半导体 > 中报预增 > 机器人/储能
# Within each sector: price < 40 first
sector_order = {'半导体': 0, '中报预增': 1, '机器人': 2, '储能': 2}
pool.sort(key=lambda x: (sector_order.get(x['sector'], 9), 0 if x['price'] < 40 else 1, -x.get('marketCapYi', 0)))

print(f'Final pool size: {len(pool)}')
print(f'Price < 40: {sum(1 for p in pool if p["price"] < 40)}')
print(f'Semiconductor: {sum(1 for p in pool if p["sector"] == "半导体")}')
print(f'中报预增: {sum(1 for p in pool if p["sector"] == "中报预增")}')
print(f'机器人: {sum(1 for p in pool if p["sector"] == "机器人")}')
print(f'储能: {sum(1 for p in pool if p["sector"] == "储能")}')

# Print all < 40 candidates
print('\n=== <40元 affordable candidates ===')
for p in pool:
    if p['price'] < 40:
        print(f'{p["code"]} {p["name"]} price={p["price"]} cap={p["marketCapYi"]}Yi sector={p["sector"]}')

# Save intermediate data
with open('data/temp_pool.json', 'w', encoding='utf-8') as f:
    json.dump(pool, f, ensure_ascii=False, indent=2)
